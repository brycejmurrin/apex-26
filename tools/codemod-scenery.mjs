#!/usr/bin/env node
// codemod-scenery: port f1-game's 52 circuit scenery closures
// (js/circuits/scenery/<id>.js) to src/circuits/scenery/<id>.ts.
//
//   node tools/codemod-scenery.mjs [--f1 <path>] [--check]
//
// Each source file is `(window.TrackScenery = window.TrackScenery || {})["<id>"] =
// function (api) { ... };`. The body is copied VERBATIM (so float operation order
// and every literal are f1-game's) into `export default (api: SceneryApi) => {...}`.
// Closures that read engine globals (`TrackGeom`, `TrackSpace`, `TrackPit`) get
// them from a second parameter typed from SceneryCore, destructured under the
// f1-game names so the body stays byte-identical.
//
// The bodies are f1-game's untyped JS, so each file carries `// @ts-nocheck`:
// verbatim plain-array vectors, heterogeneous tuple tables and optional-arg local
// helpers do not survive strict + noUncheckedIndexedAccess without rewriting the
// math. Correctness is held instead by the bit-exact parity test
// (tests/unit/scenery/closures.test.ts), and the parameter types still type the
// seam for callers.
//
// f1-game is found at --f1, else $F1_GAME, else ../f1-game beside the repo root.
// --check re-derives every output in memory and exits 1 on any difference
// (changed, missing or stale files), so the codemod is safely re-runnable.

import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(ROOT, "src/circuits/scenery");

function parseArgs(argv) {
  const opts = { f1: process.env.F1_GAME || path.resolve(ROOT, "../f1-game"), check: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--check") opts.check = true;
    else if (a === "--f1") {
      const v = argv[++i];
      if (!v) throw new Error("--f1 needs a path");
      opts.f1 = path.resolve(v);
    } else if (a.startsWith("--f1=")) opts.f1 = path.resolve(a.slice(5));
    else if (a === "-h" || a === "--help") {
      process.stdout.write("usage: node tools/codemod-scenery.mjs [--f1 <path>] [--check]\n");
      process.exit(0);
    } else throw new Error(`unknown argument: ${a}`);
  }
  return opts;
}

/** Resolve f1-game's HEAD commit by reading .git directly (no git subprocess). */
function gitSha(repo) {
  let gitDir = path.join(repo, ".git");
  if (fs.statSync(gitDir).isFile()) {
    const m = /^gitdir:\s*(.+)$/m.exec(fs.readFileSync(gitDir, "utf8"));
    if (!m) throw new Error(`unreadable ${gitDir}`);
    gitDir = path.resolve(repo, m[1].trim());
  }
  const head = fs.readFileSync(path.join(gitDir, "HEAD"), "utf8").trim();
  if (!head.startsWith("ref: ")) return head;
  const ref = head.slice(5);
  // A linked worktree keeps refs in the common dir.
  const commonFile = path.join(gitDir, "commondir");
  const common = fs.existsSync(commonFile)
    ? path.resolve(gitDir, fs.readFileSync(commonFile, "utf8").trim()) : gitDir;
  for (const dir of [gitDir, common]) {
    const loose = path.join(dir, ref);
    if (fs.existsSync(loose)) return fs.readFileSync(loose, "utf8").trim();
  }
  const packed = path.join(common, "packed-refs");
  if (fs.existsSync(packed)) {
    for (const line of fs.readFileSync(packed, "utf8").split("\n")) {
      const [sha, name] = line.split(" ");
      if (name === ref && sha) return sha;
    }
  }
  throw new Error(`cannot resolve ${ref} in ${gitDir}`);
}

// Engine globals a closure may read, and the SceneryCore member each comes from.
const ENGINE = { TrackGeom: "geom", TrackSpace: "space", TrackPit: "pit" };

/** Split one source file into its id and closure body; throws on any other shape. */
export function parseClosure(src, file) {
  const head = /\(window\.TrackScenery = window\.TrackScenery \|\| \{\}\)\["([a-z0-9_]+)"\] =\n {2}function \(api\) \{\n/.exec(src);
  if (!head) throw new Error(`${file}: no TrackScenery closure header`);
  const start = head.index + head[0].length;
  const tail = /\n *\};\n*$/.exec(src);
  const end = tail ? tail.index : -1;
  if (end < start) throw new Error(`${file}: closure does not end the file`);
  const prelude = src.slice(0, head.index);
  return { id: head[1], prelude, body: src.slice(start, end + 1) };
}

function engineUse(body) {
  // Ignore comments: several closures NAME TrackPit/TrackSpace in prose only.
  const code = body.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");
  return Object.keys(ENGINE).filter((g) => new RegExp(`\\b${g}\\.`).test(code));
}

function render(f1) {
  const require = createRequire(import.meta.url);
  const { CIRCUITS, sceneryPath } = require(path.join(f1, "tools/manifest.cjs"));
  const sha = gitSha(f1);
  const files = new Map();
  const warn = "// GENERATED by tools/codemod-scenery.mjs: do not edit; re-run the codemod.";
  for (const id of CIRCUITS) {
    const rel = sceneryPath(id);
    const src = fs.readFileSync(path.join(f1, rel), "utf8");
    const c = parseClosure(src, rel);
    if (c.id !== id) throw new Error(`${rel} registers "${c.id}"`);
    const uses = engineUse(c.body);
    const params = uses.length
      ? `api: SceneryApi, { ${uses.map((g) => `${ENGINE[g]}: ${g}`).join(", ")} }: SceneryEngine`
      : "api: SceneryApi";
    files.set(path.join(OUT_DIR, `${id}.ts`), [
      "// @ts-nocheck",
      warn,
      `// Source: f1-game ${rel} @ ${sha}`,
      `import type { SceneryApi } from "../../contracts/scenery";`,
      ...(uses.length ? [`import type { SceneryEngine } from "./engine";`] : []),
      "",
      `export default (${params}): void => {`,
      c.body + "};",
      "",
    ].join("\n"));
  }
  files.set(path.join(OUT_DIR, "index.ts"), [
    warn,
    `// Source: f1-game tools/manifest.cjs CIRCUITS @ ${sha}`,
    "// Lazy: a session imports the ONE circuit it builds (f1-game LAZY_SCENERY).",
    `import type { SceneryClosure } from "./engine";`,
    "",
    "export const SCENERY: { readonly [id: string]: () => Promise<{ default: SceneryClosure }> } = {",
    ...CIRCUITS.map((id) => `  ${/^[a-z_][a-z0-9_]*$/.test(id) ? id : JSON.stringify(id)}: () => import("./${id}"),`),
    "};",
    "",
  ].join("\n"));
  return { sha, files };
}

function main() {
  const opts = parseArgs(process.argv.slice(2));
  const { sha, files } = render(opts.f1);
  const stale = fs.existsSync(OUT_DIR)
    ? fs.readdirSync(OUT_DIR).filter((f) => f.endsWith(".ts") && f !== "engine.ts")
        .map((f) => path.join(OUT_DIR, f)).filter((f) => !files.has(f))
    : [];
  if (opts.check) {
    const bad = [];
    for (const [f, text] of files) if (!fs.existsSync(f) || fs.readFileSync(f, "utf8") !== text) bad.push(f);
    bad.push(...stale);
    if (bad.length) {
      process.stderr.write(`codemod-scenery --check: ${bad.length} file(s) out of date vs f1-game ${sha}:\n`);
      for (const f of bad) process.stderr.write(`  ${path.relative(ROOT, f)}\n`);
      process.exit(1);
    }
    process.stdout.write(`codemod-scenery --check: ${files.size} files match f1-game ${sha}\n`);
    return;
  }
  fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const f of stale) fs.rmSync(f);
  for (const [f, text] of files) fs.writeFileSync(f, text);
  process.stdout.write(`codemod-scenery: wrote ${files.size} files from f1-game ${sha}\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
