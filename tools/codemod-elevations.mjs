#!/usr/bin/env node
// Bake f1-game's generated js/track/circuit-elevations.js (tools/gen/bake-elevation.mjs:
// SRTM 30 m profiles, 64 samples by arc fraction) into src/track/core/elevations.ts.
// The source is parsed as TEXT (object literal of number arrays), never executed, and
// every number is copied as its source literal so the doubles are identical.
//
// usage: node tools/codemod-elevations.mjs [path/to/f1-game]   (default ../f1-game)
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { resolve } from "node:path";

const root = resolve(process.argv[2] || "../f1-game");
const file = "js/track/circuit-elevations.js";
const src = readFileSync(resolve(root, file), "utf8");
let sha = "unknown";
try { sha = execFileSync("git", ["-C", root, "rev-parse", "HEAD"], { encoding: "utf8" }).trim(); } catch { /* not a checkout */ }

const open = src.indexOf("const CircuitElevations = {");
if (open < 0) throw new Error(`${file}: no CircuitElevations literal`);
const body = src.slice(src.indexOf("{", open) + 1, src.indexOf("\n};", open));
const rows = [];
const re = /^\s*([a-z_][a-z0-9_]*)\s*:\s*\[([^\]]*)\]\s*,?\s*$/gm;
let m;
while ((m = re.exec(body))) {
  const nums = m[2].split(",").map((s) => s.trim()).filter(Boolean);
  for (const s of nums) if (!/^-?\d+(\.\d+)?(e-?\d+)?$/.test(s)) throw new Error(`bad number ${s} in ${m[1]}`);
  rows.push(`  ${m[1]}: [${nums.join(", ")}],`);
}
const declared = (body.match(/^\s*[a-z_][a-z0-9_]*\s*:/gm) || []).length;
if (!rows.length || rows.length !== declared) throw new Error(`parsed ${rows.length} of ${declared} profiles`);

const out = `// GENERATED by tools/codemod-elevations.mjs: do not edit; re-run the codemod.
// Source: f1-game ${file} @ ${sha}
// Surveyed circuit elevation profiles: metres relative to the start/finish line,
// 64 samples by arc fraction around the lap (f1-game tools/gen/bake-elevation.mjs).
export const CIRCUIT_ELEVATIONS: Readonly<Record<string, readonly number[]>> = {
${rows.join("\n")}
};
`;
writeFileSync(resolve("src/track/core/elevations.ts"), out);
console.log(`wrote src/track/core/elevations.ts (${rows.length} profiles)`);
