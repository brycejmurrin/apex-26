#!/usr/bin/env node
// Writes src/race/roster/teams-data.ts from f1-game js/data/teams.js (Teams.LIST),
// loaded read-only in a Node VM. Re-runnable: node tools/codemod-teams.cjs
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const { context, load, rev } = require("./race-fixtures/vm.cjs");

const ctx = context();
load(ctx, "js/data/teams.js");
const T = vm.runInContext("Teams", ctx);
const out = `// GENERATED by tools/codemod-teams.cjs from f1-game js/data/teams.js @ ${rev()}: do not edit; re-run the codemod.
// The verified 2026 grid: 11 teams, 22 drivers. Colours are [r,g,b] 0..1; tier 0 fastest .. 4 slowest.
// Liveries are opaque here (the car lane reads them); the race reads id, short, tier, stats and drivers.
import type { TeamRecord } from "./teams";

export const TEAM_LIST: readonly TeamRecord[] = ${JSON.stringify(T.LIST, null, 2)};
`;
const dest = path.join(__dirname, "../src/race/roster/teams-data.ts");
fs.writeFileSync(dest, out);
console.log("wrote", path.relative(process.cwd(), dest), T.LIST.length, "teams");
